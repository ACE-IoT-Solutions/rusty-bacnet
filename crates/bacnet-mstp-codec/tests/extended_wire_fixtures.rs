#[test]
fn annex_x4_complete_wire_image_decodes_without_encoder() {
    assert_eq!(ANNEX_X4_FRAME.len(), 522);
    let mut scratch = [0u8; MAX_EXTENDED_MPDU_DATA];
    let (frame, consumed) = decode_extended_frame(ANNEX_X4_FRAME, &mut scratch).unwrap();
    assert_eq!(consumed, ANNEX_X4_FRAME.len());
    assert_eq!(
        frame.header.frame_type,
        FrameType::ExtendedDataNotExpectingReply
    );
    assert_eq!(frame.header.destination, 0xFF);
    assert_eq!(frame.header.source, 1);
    assert_eq!(frame.header.data_length, 507);

    let mut expected = [0u8; 507];
    expected[..13].copy_from_slice(&[
        0x01, 0x20, 0xFF, 0xFF, 0x00, 0xFF, 0x10, 0x07, 0x3D, 0xFE, 0x01, 0xEF, 0x00,
    ]);
    for (index, byte) in expected[13..].iter_mut().enumerate() {
        *byte = b'A' + (index / 19) as u8;
    }
    assert_eq!(frame.data, expected);
}

// These helpers deliberately implement only the fixture construction needed
// below.  They do not call encode_extended_into, so receive-boundary tests
// still exercise the production envelope decoder independently.
fn reference_crc8(data: &[u8]) -> u8 {
    let mut crc = 0xFF;
    for &byte in data {
        crc ^= byte;
        for _ in 0..8 {
            crc = if crc & 1 != 0 {
                (crc >> 1) ^ 0x81
            } else {
                crc >> 1
            };
        }
    }
    !crc
}

fn reference_crc32k(data: &[u8]) -> u32 {
    let mut crc = 0xFFFF_FFFF;
    for &byte in data {
        crc ^= u32::from(byte);
        for _ in 0..8 {
            crc = if crc & 1 != 0 {
                (crc >> 1) ^ 0xEB31_D82E
            } else {
                crc >> 1
            };
        }
    }
    !crc
}

fn reference_cobs_xor55(data: &[u8]) -> Vec<u8> {
    let mut encoded = Vec::with_capacity(data.len() + data.len().div_ceil(254) + 1);
    let mut code_index = 0;
    encoded.push(0);
    let mut code = 1u8;
    for &byte in data {
        if byte == 0 || code == 0xFF {
            encoded[code_index] = code ^ 0x55;
            code_index = encoded.len();
            encoded.push(0);
            code = 1;
            if byte == 0 {
                continue;
            }
        }
        encoded.push(byte ^ 0x55);
        code += 1;
    }
    encoded[code_index] = code ^ 0x55;
    encoded
}

fn reference_extended_wire(payload_length: usize) -> Vec<u8> {
    let payload = vec![if payload_length == 1498 { 0 } else { 0xA5 }; payload_length];
    let encoded_data = reference_cobs_xor55(&payload);
    let crc = reference_crc32k(&encoded_data).to_le_bytes();
    let encoded_crc = reference_cobs_xor55(&crc);
    let length = encoded_data.len() + encoded_crc.len() - 2;
    let fields = [0x21, 0xFF, 0x01, (length >> 8) as u8, length as u8];
    let mut wire = vec![0x55, 0xFF];
    wire.extend_from_slice(&fields);
    wire.push(reference_crc8(&fields));
    wire.extend_from_slice(&encoded_data);
    wire.extend_from_slice(&encoded_crc);
    wire
}

#[test]
fn independent_valid_crc_boundary_fixtures_cover_supported_and_rejected_lengths() {
    for length in [501, 502, 1497, 1498] {
        let wire = reference_extended_wire(length);
        let mut scratch = [0u8; MAX_EXTENDED_MPDU_DATA + 1];
        let result = decode_extended_frame(&wire, &mut scratch);
        match length {
            502 | 1497 => {
                let (frame, consumed) = result.unwrap();
                assert_eq!(consumed, wire.len());
                assert_eq!(frame.data.len(), length);
                assert_eq!(frame.data, &vec![0xA5; length]);
            }
            501 => assert_eq!(
                result,
                Err(FrameError::ExtendedPayloadOutOfRange {
                    length,
                    minimum: MIN_EXTENDED_MPDU_DATA,
                    maximum: MAX_EXTENDED_MPDU_DATA,
                })
            ),
            1498 => assert_eq!(
                result,
                Err(FrameError::ExtendedPayloadOutOfRange {
                    length,
                    minimum: MIN_EXTENDED_MPDU_DATA,
                    maximum: MAX_EXTENDED_MPDU_DATA,
                })
            ),
            _ => unreachable!(),
        }
    }
}

#[test]
fn valid_extended_fixture_truncation_and_crc_mutations_are_rejected() {
    let wire = reference_extended_wire(502);
    let mut scratch = [0u8; MAX_EXTENDED_MPDU_DATA];
    for end in 0..wire.len() {
        assert!(decode_extended_frame(&wire[..end], &mut scratch).is_err());
    }

    let mut corrupted = wire;
    let last = corrupted.len() - 1;
    corrupted[last] ^= 1;
    assert_eq!(
        decode_extended_frame(&corrupted, &mut scratch),
        Err(FrameError::ExtendedCrcMismatch)
    );

    let mut bad_header = reference_extended_wire(502);
    bad_header[7] ^= 1;
    assert_eq!(
        decode_extended_frame(&bad_header, &mut scratch),
        Err(FrameError::HeaderCrcMismatch)
    );
}

#[test]
fn reserved_cobs_frame_types_are_rejected_across_the_entire_reserved_range() {
    let wire = reference_extended_wire(MIN_EXTENDED_MPDU_DATA);
    for raw_type in 0x22..=0x7F {
        let mut candidate = wire.clone();
        candidate[2] = raw_type;
        candidate[7] = reference_crc8(&candidate[2..7]);
        let mut scratch = [0u8; MAX_EXTENDED_MPDU_DATA];
        assert_eq!(
            decode_extended_frame(&candidate, &mut scratch),
            Err(FrameError::UnsupportedCobsFrame { raw_type })
        );
    }
}
